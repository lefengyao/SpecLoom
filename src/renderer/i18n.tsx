export type Translate = (text: string, values?: Record<string, string | number>) => string;

export function createTranslator(locale: Locale): Translate {
  return (text, values) => {
    const translated = locale === "en" ? english[text] ?? text : text;
    if (!values) return translated;
    return translated.replace(/\{(\w+)\}/g, (_, key: string) => String(values[key] ?? ""));
  };
}

const LocaleContext = createContext<Translate>(createTranslator("zh-CN"));

export function LocaleProvider({ locale, children }: { locale: Locale; children: ReactNode }) {
  return <LocaleContext.Provider value={createTranslator(locale)}>{children}</LocaleContext.Provider>;
}

export function useI18n(): Translate {
  return useContext(LocaleContext);
}
